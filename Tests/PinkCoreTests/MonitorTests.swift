import XCTest

@testable import PinkCore

@MainActor final class FakeBoard: PasteboardPort {
    var changeCount = 1
    var payload = Payload([Types.text: Data("https://github.com/a/b/pull/1".utf8)])
    var itemCount = 1
    var advertisedTypes: [[String]] { Array(repeating: Array(payload.values.keys), count: itemCount) }
    var reads = 0
    var writes = 0
    var failRead = false
    var failWrite = false
    var afterRead: (() -> Void)?
    var afterWrite: (() -> Void)?
    func read() -> Payload? {
        reads += 1
        let p = payload
        afterRead?()
        return failRead ? nil : p
    }
    func write(_ value: Payload) -> Bool {
        writes += 1
        changeCount += 1
        if failWrite { return false }
        payload = value
        afterWrite?()
        return true
    }
    func external(_ value: Payload? = nil) {
        if let value { payload = value }
        changeCount += 1
    }
}
@MainActor final class Clock: SchedulerPort {
    var tick: (@MainActor () -> Void)?
    func start(_ tick: @escaping @MainActor () -> Void) { self.tick = tick }
    func stop() { tick = nil }
}
@MainActor final class Permission: PermissionPort { var canRead = true }
@MainActor struct Builder: RepresentationBuilder {
    func build(_ reference: FormattedText, source: Payload) -> Payload? {
        Payload([Types.text: Data(reference.original.utf8), Types.html: Data(reference.html.utf8)])
    }
    func hasNamedLink(_ payload: Payload, original: String) -> Bool { false }
}
final class MonitorTests: XCTestCase {
    @MainActor func testFormatsSupportedLinksAnywhereInProse() async throws {
        let first = "https://github.com/Acme/Widget/pull/123"
        let second = "https://gitlab.com/Group/Sub/Repo/-/merge_requests/45"
        for text in [
            "Please review \(first) when ready.",
            "\(first) is ready.",
            "Please review \(first)",
            "Review (\(first)), then \(second).\nThanks 💕",
        ] {
            let board = FakeBoard()
            let clock = Clock()
            let monitor = ClipboardMonitor(
                board: board, builder: Builder(), permission: Permission(), scheduler: clock, parser: try Parser())
            monitor.enable()
            board.external(Payload([Types.text: Data(text.utf8)]))
            clock.tick?()
            XCTAssertEqual(board.writes, 1, "A text item with supported embedded URLs must be formatted")
            XCTAssertEqual(board.payload.string(Types.text), text)
            XCTAssertTrue(board.payload.string(Types.html)?.contains("Acme/Widget#123") == true)
        }
    }
    @MainActor func testBaselineSelfWriteRepeatAndRestore() async throws {
        let b = FakeBoard()
        let c = Clock()
        let p = Permission()
        let m = ClipboardMonitor(board: b, builder: Builder(), permission: p, scheduler: c, parser: try Parser())
        m.enable()
        c.tick?()
        XCTAssertEqual(b.reads, 0)
        let original = b.payload
        b.external()
        c.tick?()
        XCTAssertEqual(b.writes, 1)
        XCTAssertTrue(m.canRestore)
        c.tick?()
        XCTAssertEqual(b.writes, 1)
        m.restore()
        XCTAssertEqual(b.payload, original)
        XCTAssertFalse(m.canRestore)
        b.external(original)
        c.tick?()
        XCTAssertEqual(b.writes, 3)
        b.external(original)
        XCTAssertFalse(m.canRestore)
        m.restore()
        XCTAssertEqual(b.writes, 3)
        m.pause()
        XCTAssertNil(c.tick)
        m.enable()
        c.tick?()
        XCTAssertEqual(b.writes, 3)
    }
    @MainActor func testMarkersRaceFailurePermission() async throws {
        for marker in [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword", "com.apple.is-remote-clipboard", "public.png", "public.file-url", "custom",
        ] {
            let b = FakeBoard()
            let c = Clock()
            let p = Permission()
            let m = ClipboardMonitor(board: b, builder: Builder(), permission: p, scheduler: c, parser: try Parser())
            m.enable()
            b.payload.values[marker] = Data()
            b.external()
            c.tick?()
            XCTAssertEqual(b.reads, 0)
        }
        let b = FakeBoard()
        let c = Clock()
        let p = Permission()
        let m = ClipboardMonitor(board: b, builder: Builder(), permission: p, scheduler: c, parser: try Parser())
        m.enable()
        b.afterRead = { b.external() }
        b.external()
        c.tick?()
        XCTAssertEqual(b.writes, 0)
        b.afterRead = nil
        b.failRead = true
        b.external()
        c.tick?()
        c.tick?()
        XCTAssertEqual(b.writes, 0)
        b.failRead = false
        m.enable()
        b.failWrite = true
        b.external()
        c.tick?()
        c.tick?()
        XCTAssertEqual(b.writes, 1)
        XCTAssertEqual(m.state, .error)
        p.canRead = false
        m.enable()
        XCTAssertEqual(m.state, .permissionNeeded)
        p.canRead = true
        m.enable()
        c.tick?()
        XCTAssertEqual(b.writes, 1)
    }
}

@MainActor final class RacingBuilder: RepresentationBuilder {
    var duringBuild: (() -> Void)?
    func build(_ reference: FormattedText, source: Payload) -> Payload? {
        duringBuild?()
        return Payload([Types.text: Data(reference.original.utf8)])
    }
    func hasNamedLink(_ payload: Payload, original: String) -> Bool { false }
}
extension MonitorTests {
    @MainActor func testProseRestorationConflictsAndConstructionRace() async throws {
        let text = "Review https://github.com/a/b/pull/1 and https://gitlab.com/a/b/-/issues/2 please"
        let original = Payload([Types.text: Data(text.utf8)])
        let board = FakeBoard()
        let clock = Clock()
        let builder = RacingBuilder()
        let monitor = ClipboardMonitor(
            board: board, builder: builder, permission: Permission(), scheduler: clock, parser: try Parser())
        monitor.enable()
        board.external(original)
        builder.duringBuild = { board.external() }
        clock.tick?()
        XCTAssertEqual(board.writes, 0)
        builder.duringBuild = nil
        board.external(original)
        clock.tick?()
        XCTAssertTrue(monitor.canRestore)
        let writes = board.writes
        clock.tick?()
        XCTAssertEqual(board.writes, writes)
        monitor.restore()
        XCTAssertEqual(board.payload, original)
        board.external(
            Payload([
                Types.text: Data(text.utf8), Types.url: Data("https://github.com/a/b/pull/1".utf8),
            ]))
        clock.tick?()
        XCTAssertEqual(board.writes, writes + 1)
        XCTAssertFalse(monitor.canRestore)
    }

    @MainActor func testExternalChangeDuringConstructionAndConflictingURL() async throws {
        let b = FakeBoard()
        let c = Clock()
        let p = Permission()
        let builder = RacingBuilder()
        let m = ClipboardMonitor(board: b, builder: builder, permission: p, scheduler: c, parser: try Parser())
        m.enable()
        builder.duringBuild = { b.external() }
        b.external()
        c.tick?()
        XCTAssertEqual(b.writes, 0)
        builder.duringBuild = nil
        b.payload.values[Types.url] = Data("https://github.com/a/b/pull/2".utf8)
        b.external()
        c.tick?()
        XCTAssertEqual(b.writes, 0)
        p.canRead = false
        c.tick?()
        XCTAssertEqual(m.state, .permissionNeeded)
        XCTAssertNil(c.tick)
    }
    @MainActor func testPauseAndWakeInvalidateSnapshot() async throws {
        let b = FakeBoard()
        let c = Clock()
        let p = Permission()
        let m = ClipboardMonitor(board: b, builder: Builder(), permission: p, scheduler: c, parser: try Parser())
        m.enable()
        b.external()
        c.tick?()
        XCTAssertTrue(m.canRestore)
        m.baseline()
        XCTAssertFalse(m.canRestore)
        let fresh = Payload([Types.text: Data("https://github.com/a/b/pull/1".utf8)])
        b.external(fresh)
        c.tick?()
        XCTAssertTrue(m.canRestore)
        m.pause()
        XCTAssertFalse(m.canRestore)
        m.restore()
        XCTAssertEqual(b.writes, 2)
    }
}

extension MonitorTests {
    @MainActor func testExternalCopyImmediatelyAfterWriteIsNotSwallowed() async throws {
        let b = FakeBoard()
        let c = Clock()
        let p = Permission()
        let m = ClipboardMonitor(board: b, builder: Builder(), permission: p, scheduler: c, parser: try Parser())
        m.enable()
        let fresh = b.payload
        b.afterWrite = { b.external(fresh) }
        b.external()
        c.tick?()
        XCTAssertFalse(m.canRestore)
        b.afterWrite = nil
        c.tick?()
        XCTAssertEqual(b.writes, 2)
        XCTAssertTrue(m.canRestore)
    }
}

extension MonitorTests {
    @MainActor func testMultipleItemsAndChangeDuringRestoration() async throws {
        let b = FakeBoard()
        let c = Clock()
        let p = Permission()
        let m = ClipboardMonitor(board: b, builder: Builder(), permission: p, scheduler: c, parser: try Parser())
        m.enable()
        for count in [0, 2] {
            b.itemCount = count
            b.external()
            c.tick?()
            XCTAssertEqual(b.reads, 0)
            XCTAssertEqual(b.writes, 0)
        }
        b.itemCount = 1
        b.external()
        c.tick?()
        XCTAssertTrue(m.canRestore)
        let original = Payload([Types.text: Data("https://github.com/a/b/pull/2".utf8)])
        b.afterRead = { b.external(original) }
        m.restore()
        XCTAssertEqual(b.writes, 1)
        XCTAssertEqual(b.payload, original)
        XCTAssertFalse(m.canRestore)
    }
}
