import Foundation

public struct Payload: Equatable, Sendable {
    public var values: [String: Data]
    public init(_ values: [String: Data]) { self.values = values }
    public func string(_ type: String) -> String? { values[type].flatMap { String(data: $0, encoding: .utf8) } }
}
public enum Types {
    public static let text = "public.utf8-plain-text"
    public static let url = "public.url"
    public static let html = "public.html"
    public static let rtf = "public.rtf"
    public static let own = "io.refpaste.self.v1"
    public static let generated = "org.nspasteboard.AutoGeneratedType"
    public static let allowed: Set<String> = [text, url, html, rtf]
}
@MainActor public protocol PasteboardPort: AnyObject {
    var changeCount: Int { get }
    var advertisedTypes: [[String]] { get }
    func read() -> Payload?
    func write(_ payload: Payload) -> Bool
}
@MainActor public protocol RepresentationBuilder {
    func build(_ reference: Reference) -> Payload?
    func hasNamedLink(_ payload: Payload, original: String) -> Bool
}
@MainActor public protocol PermissionPort { var canRead: Bool { get } }
@MainActor public protocol SchedulerPort {
    func start(_ tick: @escaping @MainActor () -> Void)
    func stop()
}
public enum MonitorState: String, Sendable {
    case paused = "Paused"
    case active = "Active"
    case permissionNeeded = "Permission needed"
    case error = "Error"
}

@MainActor public final class ClipboardMonitor {
    public private(set) var state: MonitorState = .paused
    public var parser: Parser
    public var onChange: (() -> Void)?
    private let board: any PasteboardPort
    private let builder: any RepresentationBuilder
    private let permission: any PermissionPort
    private let scheduler: any SchedulerPort
    private var seen: Int
    private var snapshot: Payload?
    private var writtenCount: Int?
    private var marker: Data?
    public init(
        board: any PasteboardPort, builder: any RepresentationBuilder, permission: any PermissionPort,
        scheduler: any SchedulerPort, parser: Parser
    ) {
        self.board = board
        self.builder = builder
        self.permission = permission
        self.scheduler = scheduler
        self.parser = parser
        seen = board.changeCount
    }
    public var canRestore: Bool { snapshot != nil && writtenCount == board.changeCount }
    private func invalidate() {
        snapshot = nil
        writtenCount = nil
        marker = nil
    }
    public func baseline() {
        seen = board.changeCount
        invalidate()
        onChange?()
    }
    public func enable() {
        baseline()
        state = permission.canRead ? .active : .permissionNeeded
        if state == .active { scheduler.start { [weak self] in self?.tick() } }
        onChange?()
    }
    public func pause() {
        scheduler.stop()
        invalidate()
        state = .paused
        onChange?()
    }
    public func tick() {
        guard state == .active else { return }
        guard permission.canRead else {
            scheduler.stop()
            baseline()
            state = .permissionNeeded
            onChange?()
            return
        }
        guard seen != board.changeCount else { return }
        process()
    }
    public func process() {
        guard permission.canRead else {
            state = .permissionNeeded
            onChange?()
            return
        }
        let count = board.changeCount
        seen = count
        invalidate()
        let types = board.advertisedTypes
        guard types.count == 1, !types[0].isEmpty,
            Set(types[0]).isSubset(of: Types.allowed),
            types[0].contains(Types.text) || types[0].contains(Types.url),
            board.changeCount == count
        else {
            onChange?()
            return
        }
        guard let original = board.read() else {
            scheduler.stop()
            state = .error
            onChange?()
            return
        }
        guard board.changeCount == count,
            let text = original.string(Types.text) ?? original.string(Types.url),
            original.values.values.reduce(0, { $0 + $1.count }) <= 65536,
            original.string(Types.url).map({ $0 == text }) ?? true,
            let reference = parser.parse(text), !builder.hasNamedLink(original, original: text),
            var output = builder.build(reference)
        else {
            onChange?()
            return
        }
        let token = Data(UUID().uuidString.utf8)
        output.values[Types.own] = token
        output.values[Types.generated] = Data()
        guard board.changeCount == count else {
            onChange?()
            return
        }
        if board.write(output) {
            seen = board.changeCount
            writtenCount = seen
            snapshot = original
            marker = token
        } else {
            seen = board.changeCount
            state = .error
        }
        onChange?()
    }
    public func restore() {
        guard canRestore, let original = snapshot, let expected = writtenCount,
            board.read()?.values[Types.own] == marker, board.changeCount == expected
        else {
            invalidate()
            onChange?()
            return
        }
        invalidate()
        if !board.write(original) { state = .error }
        seen = board.changeCount
        onChange?()
    }
}
